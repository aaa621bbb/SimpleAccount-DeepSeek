    /**
     * 文件"交易分类/交易类型"列值 → app 预置分类名的别名映射。
     * 仅当文件列值无法直接等于 app 分类名时做归一化；返回 null 表示无需归一化（直接用原值）。
     * 顺序优先：含关键词即命中。
