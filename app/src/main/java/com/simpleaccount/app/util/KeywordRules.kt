package com.simpleaccount.app.util

/**
 * 内置关键词规则表（终稿 4.2）。多分类同时命中按分类顺序优先：
 * 餐饮 → 交通 → 购物 → 娱乐 → 医疗 → 教育 → 居住 → 通讯（第一个命中为准）。
 */
object KeywordRules {

    /** 有序：每个元素是 (分类名, 关键词列表)。顺序即优先级。 */
    private val RULES: List<Pair<String, List<String>>> = listOf(
        "餐饮" to listOf(
            "肯德基", "麦当劳", "塔斯汀", "蜜雪冰城", "瑞幸", "星巴克", "海底捞", "美团", "饿了么",
            "外卖", "餐厅", "饭店", "烧烤", "火锅", "奶茶", "咖啡", "汉堡", "面馆", "小吃", "甜品"
        ),
        "交通" to listOf(
            "滴滴", "地铁", "公交", "高铁", "火车", "机票", "加油", "停车", "打车", "出租车",
            "网约车", "顺风车", "代驾", "高速", "过路费", "出行"
        ),
        "购物" to listOf(
            "淘宝", "天猫", "京东", "拼多多", "超市", "便利店", "商场", "优衣库", "购物",
            "菜市场", "生鲜", "沃尔玛", "山姆"
        ),
        "娱乐" to listOf(
            "电影", "KTV", "游戏", "视频会员", "爱奇艺", "腾讯视频", "哔哩哔哩", "B站", "优酷",
            "网易云", "QQ音乐", "演唱会", "剧本杀", "密室", "台球", "游乐园"
        ),
        "医疗" to listOf(
            "医院", "诊所", "药店", "体检", "医保", "挂号", "药房", "口腔", "牙科", "眼科", "急诊", "住院"
        ),
        "教育" to listOf(
            "学费", "培训", "课程", "书店", "学校", "考试", "补习", "辅导", "驾校", "考研", "网课", "教材", "文具"
        ),
        "居住" to listOf(
            "房租", "水电", "物业", "宽带", "燃气", "房东", "中介", "搬家", "家政", "保洁", "维修", "装修"
        ),
        "通讯" to listOf(
            "话费", "流量", "电信", "移动", "联通", "宽带", "充值", "月租"
        ),
    )

    /**
     * 对「商家名 + 商品名」拼接串做 contains 匹配。
     * @return 命中的分类名，未命中返回 null。
     */
    fun classify(text: String): String? {
        // 去空、统一判大小写无关（原中文无大小写，但保险起见转小写匹配英文如KTV/B站）
        val t = text.lowercase()
        for ((category, keywords) in RULES) {
            for (kw in keywords) {
                if (t.contains(kw.lowercase())) {
                    return category
                }
            }
        }
        return null
    }
}
